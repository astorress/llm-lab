"""Fuentes del corpus de pre-entrenamiento: locales (JSONL) y Hugging Face (streaming).

Cada fuente se describe en ``configs/data.yaml`` y se convierte aquí en un
iterador de documentos ``{"text", "domain", "source", "lang"}`` ya filtrados
(calidad + dominio + filtros específicos como categorías de arXiv o heurísticas
de código). El builder (``scripts/build_pretrain_corpus.py``) solo consume
estos iteradores y corta cuando llena el presupuesto de tokens.

``datasets`` se importa de forma perezosa: las fuentes locales funcionan sin él.
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from pathlib import Path

from llm_lab.data.cleaning import QualityConfig, normalize_text, quality_score
from llm_lab.data.domains import DomainClassifier

__all__ = ["iter_source", "approx_tokens"]

# Para presupuestar sin tokenizar: ~4 caracteres por token en BPE byte-level
# (inglés ≈ 4.2, español ≈ 3.8, código ≈ 3.5). El conteo exacto lo hace
# scripts/tokenize_corpus.py y queda en meta.json.
CHARS_PER_TOKEN = 4.0


def approx_tokens(text: str) -> int:
    return int(len(text) / CHARS_PER_TOKEN) + 1


def _iter_local(spec: dict, root: Path) -> Iterator[dict]:
    path = root / spec["path"]
    if not path.exists():
        raise FileNotFoundError(
            f"No existe {path}. Genera la fuente primero (ver README → pipeline de datos)."
        )
    with path.open(encoding="utf-8") as f:
        for line in f:
            if line.strip():
                yield json.loads(line)


def _iter_hf(spec: dict) -> Iterator[dict]:
    from datasets import load_dataset

    ds = load_dataset(spec["path"], spec.get("name"), split="train", streaming=True)
    yield from ds


def _arxiv_ok(row: dict, allowed: set[str]) -> bool:
    cats = row.get("categories") or []
    # El dataset guarda ["cs.LG stat.ML"]: una lista con un string separado por espacios.
    flat = " ".join(cats).split() if isinstance(cats, list) else str(cats).split()
    return any(c in allowed for c in flat)


def _code_ok(row: dict, rules: dict) -> bool:
    if rules.get("skip_autogenerated") and row.get("autogenerated"):
        return False
    allowed = rules.get("allowed_licenses")
    if allowed and str(row.get("license", "")).lower() not in allowed:
        return False
    if row.get("line_max", 0) > rules.get("max_line_max", 10**9):
        return False
    return row.get("alpha_frac", 1.0) >= rules.get("min_alpha_frac", 0.0)


def iter_source(
    name: str,
    spec: dict,
    root: Path,
    classifier: DomainClassifier,
    quality_cfg: QualityConfig | None = None,
    min_quality: float = 0.5,
) -> Iterator[dict]:
    """Itera documentos limpios y etiquetados de una fuente.

    Args:
        name: nombre de la fuente (clave en data.yaml).
        spec: su configuración.
        root: raíz del proyecto (para rutas locales).
        classifier: clasificador léxico de dominio.
        quality_cfg / min_quality: filtro de calidad estilo Gopher.
    """
    rows = _iter_local(spec, root) if spec["type"] == "local_jsonl" else _iter_hf(spec)
    text_field = spec.get("text_field", "text")
    title_field = spec.get("title_field")
    min_hits = spec.get("min_domain_hits", 0)
    use_quality = spec.get("quality_filter", True)
    min_field = spec.get("min_field", {})
    arxiv_cats = set(spec.get("arxiv_categories", []))
    code_rules = spec.get("code_filter")

    for row in rows:
        if any(row.get(k, 0) < v for k, v in min_field.items()):
            continue
        if arxiv_cats and not _arxiv_ok(row, arxiv_cats):
            continue
        if code_rules and not _code_ok(row, code_rules):
            continue

        text = row.get(text_field) or ""
        if title_field and row.get(title_field):
            text = f"{row[title_field].strip()}\n\n{text}"
        # El código conserva su indentación: normalize_text colapsa espacios.
        text = text.strip() if spec.get("lang") == "code" else normalize_text(text)
        if len(text) < 200:
            continue
        if use_quality and quality_score(text, quality_cfg) < min_quality:
            continue

        match = classifier.classify(text)
        if match.total_hits < min_hits:
            continue
        domain = (
            row.get(spec["domain_field"]) if spec.get("domain_field") else None
        ) or spec.get("default_domain") or match.domain or "general"

        yield {"text": text, "domain": domain, "source": name, "lang": spec.get("lang", "es")}
